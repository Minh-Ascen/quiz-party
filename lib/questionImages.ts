/**
 * Tự động tìm hình ảnh minh họa phù hợp nhất cho bất kỳ câu hỏi nào
 */
export function resolveQuestionImage(question: Partial<Question> | null | undefined): string {
  if (!question) return VERIFIED_IMAGES.cinema;

  // 1. Nếu câu hỏi đã có sẵn image_url hợp lệ -> ưu tiên sử dụng
  if (question.image_url && question.image_url.startsWith("http")) {
    return question.image_url;
  }

  // 2. Nếu câu hỏi có YouTube Video ID -> có thể lấy ảnh thumbnail HD từ YouTube
  if (question.youtube_video_id) {
    return `https://img.youtube.com/vi/${question.youtube_video_id}/hqdefault.jpg`;
  }

  // 3. Đối chiếu từ khóa trong nội dung câu hỏi (prompt) và các đáp án (options)
  const searchText = `${question.prompt || ""} ${(question.options || []).join(" ")}`.toLowerCase();

  for (const rule of KEYWORD_IMAGE_RULES) {
    for (const kw of rule.keywords) {
      if (searchText.includes(kw.toLowerCase())) {
        const url = VERIFIED_IMAGES[rule.imageKey];
        if (url) return url;
      }
    }
  }

  // 4. Fallback về hình ảnh đặc trưng của chủ đề
  if (question.category && CATEGORY_DEFAULT_IMAGES[question.category]) {
    return CATEGORY_DEFAULT_IMAGES[question.category];
  }

  return VERIFIED_IMAGES.cinema;
}
